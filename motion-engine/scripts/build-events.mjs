// (soundevents) The event timeline (frontend/src/motionEngine/events.js) as ONE plain Node module, run as `node <bundle> [project.json]`:
//   with a 3D Scene's part (world3d/eventsCli.mjs, world3d/sceneEvents.js): html/world3d-lab/build.mjs --host →
//                     frontend/public/world3d/world3d-events.mjs. backend/sound_events.py runs it with the app's own Electron as node (the
//                     frontend build copies it into the packed app's frontend-dist/world3d/); the 3D plugin carries it too.
//   without it (motionEngine/eventsCli.mjs, no 3D code: the Apache package): node scripts/build-events.mjs --2d --out
//                     dist/greenlight-motion-events.mjs (prepare.mjs; the CLI's `events` on a project without a Scene)
// The timeline needs the editor's keyframe maths, not its renderer, but those modules import it (gsapTransitions → three.js, the
// transition packages, React): the same empty stand-ins as build-script.mjs take their place. --check proves that changes nothing: the
// fixtures' timelines with the stand-ins and with the full app code are byte for byte the same.
//   node motion-engine/scripts/build-events.mjs --out <file.mjs> [--check <project.json> …]
import { build } from '../../frontend/node_modules/esbuild/lib/main.js';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const ENTRY = path.resolve(here, '../../frontend/src/world3d/eventsCli.mjs');
const ENTRY_2D = path.resolve(here, '../../frontend/src/motionEngine/eventsCli.mjs');
const STUB = /^(three|three\/.*|react|react-dom|react\/.*|mp4box)$|[\\/](advancedTransitions|builtinTransitionPackages|transitionPackageRuntime|materialFactory|videoRenderer)(\.js)?$/;

// (camlayer) The 3D bundle keeps three.js itself: a Scene with no camera of its own is filmed by the project's Camera layer, whose pose is
// three's vector maths (projectCamera.js through cameraLayerShot.js). The 2D bundle carries no 3D code and keeps the stand-in.
export async function standIns({ keepThree = false } = {}) {
  // three.js stands in with its OWN export names, each one inert function that can also be constructed (build-script.mjs)
  const names = Object.keys(await import(pathToFileURL(path.resolve(here, '../../frontend/node_modules/three/build/three.module.js')).href));
  return {
    name: 'renderer-stand-ins',
    setup(b) {
      b.onResolve({ filter: /.*/ }, (args) => (STUB.test(args.path) && !(keepThree && /^three(\/.*)?$/.test(args.path)) ? { path: args.path, namespace: 'stand-in' } : null));
      b.onLoad({ filter: /.*/, namespace: 'stand-in' }, (args) => (args.path === 'three'
        ? { contents: `function f() {}\nexport { ${names.map((n) => `f as ${n}`).join(', ')} };`, loader: 'js' }
        : { contents: 'const f = () => undefined; module.exports = new Proxy(f, { get: () => f });', loader: 'js' }));
    },
  };
}

/** Builds the bundle into `out` (with the stand-ins unless `full`; without the Scene's part with `twoD`); returns the esbuild result. */
export async function buildEvents(out, { full = false, metafile = false, minify = true, twoD = false } = {}) {
  const r = await build({
    entryPoints: [twoD ? ENTRY_2D : ENTRY], outfile: out, bundle: true, format: 'esm', platform: 'node', target: 'node18', minify, sourcemap: false,
    logLevel: 'warning', legalComments: 'none', metafile, define: { 'import.meta.env': '{}' },
    banner: { js: `// GENERATED by motion-engine/scripts/build-events.mjs from frontend/src/${twoD ? 'motionEngine' : 'world3d'}/eventsCli.mjs — do not edit.` },
    plugins: full ? [] : [await standIns({ keepThree: !twoD })],
  });
  return r;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const at = process.argv.indexOf('--out');
  if (at < 0 || !process.argv[at + 1]) { console.error('usage: node build-events.mjs [--2d] --out <file.mjs> [--check <project.json> …]'); process.exit(2); }
  const OUT = path.resolve(process.argv[at + 1]);
  const twoD = process.argv.includes('--2d');
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  const built = await buildEvents(OUT, { twoD, metafile: twoD });
  // the Apache package carries no 3D code: its bundle must not read a file of the world's
  const world = twoD ? Object.keys(built.metafile.inputs).filter((f) => /(^|[\\/])(world3d|sim)[\\/]/.test(f)) : [];
  if (world.length) { console.error(`build-events: the 2D bundle carries 3D code: ${world.join(', ')}`); process.exit(1); }
  console.log(`event timeline → ${path.relative(process.cwd(), OUT)} (${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`);
  const ck = process.argv.indexOf('--check');
  if (ck > 0) {
    const files = process.argv.slice(ck + 1).filter((a) => !a.startsWith('--'));
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'events-check-'));
    const fullOut = path.join(dir, 'full.mjs');
    await buildEvents(fullOut, { full: true, twoD });
    let bad = 0;
    for (const f of files) {
      const a = execFileSync(process.execPath, [OUT, f], { maxBuffer: 1 << 28 });
      const b = execFileSync(process.execPath, [fullOut, f], { maxBuffer: 1 << 28 });
      const same = a.equals(b);
      if (!same) bad += 1;
      console.log(`${same ? 'same' : 'DIFFERENT'}  ${path.basename(f)}  (${JSON.parse(a).events.length} events)`);
    }
    fs.rmSync(dir, { recursive: true, force: true });
    if (bad) process.exit(1);
  }
}
