// The page clock an HTML layer's page runs on, as a JavaScript module for the engine bundle.
//
// The clock is written once, in backend/html_clips.py (CLOCK_SCRIPT): the app's bake and its live layer install it before
// any page script, and step the page with window.__glHtmlClipSeek. Outside the app there is no backend to put it into the
// page, so the engine does (frontend/src/motionEngine/htmlPages.js) with this copy of the same text. Run before the engine
// bundle is built (frontend `npm run build:motion-engine`); `--check` only says whether the copy is the backend's text
// (frontend/src/motionEngine/htmlPageText.test.mjs).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const source = path.join(repo, 'backend', 'html_clips.py');
const target = path.join(repo, 'frontend', 'src', 'motionEngine', 'htmlClipClock.js');

/** The text of CLOCK_SCRIPT in html_clips.py: a raw triple-quoted string, so its bytes are the script's. */
export function clockFromBackend(py = readFileSync(source, 'utf8')) {
  const open = 'CLOCK_SCRIPT = r"""';
  const from = py.indexOf(open);
  const to = from < 0 ? -1 : py.indexOf('"""', from + open.length);
  if (from < 0 || to < 0) throw new Error(`no CLOCK_SCRIPT = r"""…""" in ${source}`);
  const text = py.slice(from + open.length, to);
  if (!text.includes('__glHtmlClipSeek')) throw new Error('CLOCK_SCRIPT has no __glHtmlClipSeek: not the page clock');
  // It goes into a page inside <script>…</script>, as the backend puts it there.
  if (/<\/script/i.test(text)) throw new Error('CLOCK_SCRIPT holds "</script": it would end the tag it is put in');
  return text;
}

export function clockModule(text) {
  return `// GENERATED by motion-engine/scripts/build-html-clock.mjs from backend/html_clips.py (CLOCK_SCRIPT). Do not edit:
// change the clock there and run the script (the engine's build does).
//
// The deterministic clock of an HTML layer's page: time moves only when the engine calls window.__glHtmlClipSeek(ms).
export const HTML_CLIP_CLOCK = ${JSON.stringify(text)};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = clockModule(clockFromBackend());
  const have = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (have !== next) { console.error(`${path.relative(repo, target)} is not the backend's clock: run node motion-engine/scripts/build-html-clock.mjs`); process.exit(1); }
    console.log('the engine\'s page clock is the backend\'s');
  } else if (have !== next) {
    writeFileSync(target, next);
    console.log(`wrote ${path.relative(repo, target)}`);
  }
}
