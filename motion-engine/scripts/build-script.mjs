// The scene script converter as one plain ES module (frontend/src/motionEngine/sceneScriptBundle.js → --out): the
// converter with the Video Editor's own animation presets, its guide, the media header readers and the template check.
// The SAME bundle for every way in:
//   the npm package:   node scripts/build-script.mjs --out dist/greenlight-motion-script.mjs   (prepare.mjs; `script` in the CLI)
//   the connector:     node ../../motion-engine/scripts/build-script.mjs --out src/vendor/sceneScript.mjs   (wrangler [build], npm test)
// The preset maths needs none of the renderer, but its modules import it (gsapTransitions → three.js, the transition
// packages, React): those imports are replaced by empty stand-ins. --check proves that changes nothing: every preset,
// applied with the stand-ins and with the full app code, gives identical keyframes, and so does a whole scene script.
// --inputs <file.json> writes the source files it read (repo-relative): the public source export copies them.
import { build } from '../../frontend/node_modules/esbuild/lib/main.js';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const ENGINE_SRC = path.resolve(here, '../../frontend/src/motionEngine');
const VE = path.resolve(here, '../../frontend/src/components/videoEditor');
const at = process.argv.indexOf('--out');
if (at < 0 || !process.argv[at + 1]) { console.error('usage: node build-script.mjs --out <file.mjs> [--check]'); process.exit(2); }
const OUT = path.resolve(process.argv[at + 1]);

const STUB = /^(three|three\/.*|react|react-dom|react\/.*)$|[\\/](advancedTransitions|builtinTransitionPackages|transitionPackageRuntime|materialFactory|videoRenderer)(\.js)?$/;
// three.js itself stands in with its OWN export names, each one inert function that can also be constructed: a module
// that builds three.js objects as it loads (projectCamera.js: `const _pfMat = new THREE.Matrix4()`) reads them off the
// namespace (`import * as THREE`), which copies only the names a module really exports
const THREE_NAMES = Object.keys(await import(pathToFileURL(path.resolve(here, '../../frontend/node_modules/three/build/three.module.js')).href));
const stubs = {
  name: 'renderer-stand-ins',
  setup(b) {
    b.onResolve({ filter: /.*/ }, (args) => (STUB.test(args.path) ? { path: args.path, namespace: 'stand-in' } : null));
    // an empty module whose every named import is an inert function (never called by the preset maths)
    b.onLoad({ filter: /.*/, namespace: 'stand-in' }, (args) => (args.path === 'three'
      ? { contents: `function f() {}\nexport { ${THREE_NAMES.map((n) => `f as ${n}`).join(', ')} };`, loader: 'js' }
      : { contents: 'const f = () => undefined; module.exports = new Proxy(f, { get: () => f });', loader: 'js' }));
  },
};
const opts = (entry, plugins) => ({ ...entry, bundle: true, format: 'esm', platform: 'neutral', write: false, loader: { '.md': 'text' },
  mainFields: ['module', 'main'], conditions: ['import', 'module', 'default'], logLevel: 'silent', plugins, define: { 'import.meta.env': '{}' } });
const MAIN = { entryPoints: [path.join(ENGINE_SRC, 'sceneScriptBundle.js')] };

const lean = await build({ ...opts(MAIN, [stubs]), metafile: true });
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, `// GENERATED by motion-engine/scripts/build-script.mjs from frontend/src/motionEngine/sceneScriptBundle.js — do not edit.\n${lean.outputFiles[0].text}`);
console.log(`scene script → ${path.relative(process.cwd(), OUT)} (${(lean.outputFiles[0].text.length / 1024).toFixed(0)} KB)`);
const inputsAt = process.argv.indexOf('--inputs');
if (inputsAt > 0) {
  const repo = path.resolve(here, '../..');
  const sources = Object.keys(lean.metafile.inputs).filter((f) => !f.startsWith('stand-in:') && !f.includes('node_modules'))
    .map((f) => path.relative(repo, path.resolve(f)).split(path.sep).join('/')).filter((f) => !f.startsWith('..')).sort();
  fs.writeFileSync(path.resolve(process.argv[inputsAt + 1]), `${JSON.stringify({ sources }, null, 1)}\n`);
}

if (process.argv.includes('--check')) {
  const tmp = (name, text) => { const p = path.join(fs.mkdtempSync(path.join(process.env.TMPDIR || '/tmp', 'ss-')), name); fs.writeFileSync(p, text); return p; };
  // the presets, applied one by one
  const PRESETS = { stdin: { contents: `
export { PRESETS as TEXT_PRESETS } from ${JSON.stringify(path.join(VE, 'textAnimatorPresets.js'))};
export { CLASSIC_PRESETS } from ${JSON.stringify(path.join(VE, 'textAnimatorClassicPresets.js'))};
export { presetPatch } from ${JSON.stringify(path.join(VE, 'textAnimatorPresetPatch.js'))};
export { KEYFRAME_PRESETS, KFP_DEFAULT_LENGTH, kfpVariants, resolvePresetVariant, applyKeyframePreset } from ${JSON.stringify(path.join(VE, 'keyframePresetCatalog.js'))};
`, resolveDir: VE, loader: 'js' } };
  const A = await import(pathToFileURL(tmp('lean.mjs', (await build(opts(PRESETS, [stubs]))).outputFiles[0].text)).href);
  const B = await import(pathToFileURL(tmp('full.mjs', (await build(opts(PRESETS, []))).outputFiles[0].text)).href);
  const item = { id: 'x', textContent: 'Hello motion world', textFontSize: 96, trimStart: 0, trimEnd: 4, propertyKeyframes: {} };
  const runs = [];
  for (const kind of ['in', 'out']) {
    for (const p of A.kfpVariants(A.KEYFRAME_PRESETS, kind)) {
      const q = B.kfpVariants(B.KEYFRAME_PRESETS, kind).find((v) => v.id === p.id);
      const dirs = Array.isArray(p.directions) ? p.directions : [null];
      for (const d of dirs) runs.push([`${kind}:${p.id}:${d}`, A.applyKeyframePreset(item, A.resolvePresetVariant(p, d), { startPct: 0, endPct: 40 }), B.applyKeyframePreset(item, B.resolvePresetVariant(q, d), { startPct: 0, endPct: 40 })]);
    }
  }
  for (const p of [...A.TEXT_PRESETS, ...A.CLASSIC_PRESETS]) {
    const q = [...B.TEXT_PRESETS, ...B.CLASSIC_PRESETS].find((v) => v.id === p.id);
    runs.push([`text:${p.id}`, A.presetPatch(item, p, { clipSec: 4, fontPx: 96, mode: 'replace' }), B.presetPatch(item, q, { clipSec: 4, fontPx: 96, mode: 'replace' })]);
  }
  // a whole scene script (the guide's own example), converted by this bundle and by one with the full app code
  const S = await import(pathToFileURL(OUT).href);
  const F = await import(pathToFileURL(tmp('full-script.mjs', (await build(opts(MAIN, []))).outputFiles[0].text)).href);
  const example = JSON.parse(S.scriptFormatGuide('cli').match(/```json\n([\s\S]*?)\n```/)[1]);
  runs.push(['script:guide example', S.compileScript(example, null, new Map()), F.compileScript(example, null, new Map())]);
  const differ = runs.filter(([, a, b]) => JSON.stringify(a) !== JSON.stringify(b)).map(([k]) => k);
  console.log(`check: ${runs.length} preset applications and scripts, ${differ.length} differ${differ.length ? `: ${differ.slice(0, 8).join(', ')}` : ''}`);
  if (differ.length) process.exit(1);
}
